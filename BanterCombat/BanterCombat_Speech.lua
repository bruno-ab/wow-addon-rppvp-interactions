local function cloneApply(node, map)
  if type(node) ~= "table" then
    if type(node) == "string" then
      return map[node] or node
    end
    return node
  end
  local copy = {}
  for k, v in pairs(node) do
    copy[k] = cloneApply(v, map)
  end
  return copy
end

