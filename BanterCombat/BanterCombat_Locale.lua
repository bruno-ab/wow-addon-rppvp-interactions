local ALIAS = {
  enGB = "enUS",
  ptPT = "ptBR",
}

ns.LOCALE_ORDER = {
  "auto", "ptBR", "enUS", "deDE", "esES", "esMX", "frFR", "itIT", "koKR", "ruRU", "zhCN", "zhTW",
}

local function resolveCode(code)
  code = ALIAS[code] or code
  if catalogs[code] then
    return code
  end
  return nil
end

ns.LocaleCode = resolveCode(locale) or "enUS"

setmetatable(ns.L, {
  __index = function(_, key)
    local pack = catalogs[ns.LocaleCode] or enUS
    return pack[key] or enUS[key] or key
  end,
})

function ns.SetLocale(code)
  local resolved = resolveCode(code)
  if resolved then
    ns.LocaleCode = resolved
  end
end

function ns.LocaleName(code)
  if code == "auto" then
    return ns.L.LOCALE_AUTO
  end
  local resolved = resolveCode(code) or code
  local pack = catalogs[ns.LocaleCode] or enUS
  return pack["LOCALE_" .. resolved] or enUS["LOCALE_" .. resolved] or resolved
end

function ns.ApplySavedLocale()
  local choice = "auto"
  if ns.Options and ns.Options.Get then
    choice = ns.Options.Get().locale or "auto"
  end
  if choice == "auto" or choice == "" then
    ns.SetLocale(GetLocale and GetLocale() or "enUS")
  else
    ns.SetLocale(choice)
  end
end

